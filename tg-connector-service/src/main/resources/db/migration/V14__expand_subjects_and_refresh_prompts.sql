WITH refreshed_groups AS (
    UPDATE curator_vk_groups AS groups
    SET config_version = nextval('vk_group_config_version_seq'),
        pending_config_event_id = gen_random_uuid(),
        status = 'PENDING',
        last_error = NULL
    FROM curators
    JOIN subjects ON subjects.id = curators.subject_id
    WHERE groups.curator_id = curators.id
      AND groups.status <> 'REMOVING'
    RETURNING
        groups.pending_config_event_id AS event_id,
        groups.config_version,
        groups.vk_group_id,
        groups.vk_token,
        groups.vk_secret,
        groups.vk_confirmation_code,
        subjects.system_prompt
)
INSERT INTO vk_group_config_outbox (
    event_id,
    vk_group_id,
    config_version,
    payload,
    created_at,
    attempts,
    next_attempt_at
)
SELECT
    event_id,
    vk_group_id,
    config_version,
    jsonb_build_object(
        'eventId', event_id,
        'configVersion', config_version,
        'action', 'UPSERT',
        'vkGroupId', vk_group_id,
        'vkToken', vk_token,
        'vkSecret', vk_secret,
        'vkConfirmationCode', vk_confirmation_code,
        'systemPrompt', system_prompt
    )::text,
    CURRENT_TIMESTAMP,
    0,
    CURRENT_TIMESTAMP
FROM refreshed_groups;
